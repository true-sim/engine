package com.truesim.engine.render;

import static org.lwjgl.system.MemoryStack.stackPush;
import static org.lwjgl.system.MemoryUtil.memPutLong;

import com.truesim.annotations.AllowAllocation;
import com.truesim.engine.graph.Buffer;
import com.truesim.engine.graph.BufferAccess;
import com.truesim.engine.graph.GraphBuilder;
import com.truesim.engine.graph.PassContext;
import com.truesim.engine.render.layout.IndirectLightLayout;
import com.truesim.engine.vulkan.Commands;
import com.truesim.engine.vulkan.ShaderVariants;
import com.truesim.engine.vulkan.VulkanDevice;
import java.lang.foreign.Arena;
import java.lang.foreign.MemorySegment;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import org.lwjgl.system.MemoryStack;

/**
 * The shading hooks the shaders were built with (hooks.slang; README, "Writing a shading hook"): each by its index, as
 * the generated dispatch numbers them (bit {@code index % 32} of specialization constant {@code FIRST_CONSTANT + index
 * / 32}), with its parameters' record. A listing is generated by the build ({@code slang.shadingHooks}): the engine's
 * own, {@link EngineShadingHooks}, holds its hooks; a project adding hooks (a library's, a game's) gets one holding
 * every hook it sees, with its libraries' shaders that shade rebuilt with them, which {@link #use} installs on the
 * device in place of the libraries' own. There is no limit on the hooks.
 *
 * <p>A hook's technique adds it to its view with {@link #add}: its parameters, from a {@link ShadingHookSource} (a
 * technique's settings, a scene component's values), go up each frame into a record of the view's, whose address the
 * view's indirect-light table holds after its fields.
 *
 * <pre>{@code
 * ShadingHooks.use(device, GameHooks.HOOKS);                      // before the first frame
 * // In a technique modifying Keys.INDIRECT_LIGHT:
 * ShadingHooks.of(device).add(g, "game.fog", ShadingHookSource.of(() -> fog));
 * }</pre>
 */
public final class ShadingHooks {

    /** The id of the first specialization constant of the hooks' bits: hooks.properties' {@code constant.first}. */
    public static final int FIRST_CONSTANT = 3;

    private final String name;
    private final List<String> hooks;
    private final Class<?>[] parameters;
    private final int[] bytes;
    private final int words;
    private final String[] replaced;

    private ShadingHooks(String name, List<String> hooks, Class<?>[] parameters, int[] bytes, int words,
        String[] replaced) {
        this.name = name;
        this.hooks = hooks;
        this.parameters = parameters;
        this.bytes = bytes;
        this.words = words;
        this.replaced = replaced;
    }

    /**
     * A listing named {@code name}: {@code hooks} by index, each one's parameters' record class (null: none) and
     * bytes, the id of the first of its {@code words} specialization constants, and {@code replaced}, pairs of a
     * library's shader and its rebuilt variant (classpath resources). Called by the generated listings.
     */
    @AllowAllocation("made once, by a generated class")
    public static ShadingHooks of(String name, String[] hooks, Class<?>[] parameters, int[] bytes, int firstConstant,
        int words, String[] replaced) {
        Objects.requireNonNull(name, "name");
        if (replaced.length % 2 != 0) {
            throw new IllegalArgumentException("Replaced shaders come in pairs: " + replaced.length);
        }
        if (parameters.length != hooks.length || bytes.length != hooks.length) {
            throw new IllegalArgumentException("A record and its bytes per hook");
        }
        if (firstConstant != FIRST_CONSTANT || words != (hooks.length + 31) / 32) {
            throw new IllegalArgumentException(name + " was built by other shading-hooks templates: constants from "
                + firstConstant + ", " + words + " of them");
        }
        return new ShadingHooks(name, List.of(hooks), parameters.clone(), bytes.clone(), words, replaced.clone());
    }

    /**
     * Installs {@code hooks} on {@code device}: its variants replace the libraries' shaders wherever they are loaded,
     * and {@link #of(VulkanDevice)} gives it. Before the first frame: pipelines made before keep their shaders.
     * Returns {@code hooks}.
     *
     * @throws IllegalArgumentException where a variant is not on the classpath
     */
    @AllowAllocation("installed once, before rendering")
    public static ShadingHooks use(VulkanDevice device, ShadingHooks hooks) {
        ShaderVariants variants = device.shaderVariants();
        for (int i = 0; i < hooks.replaced.length; i += 2) {
            String variant = hooks.replaced[i + 1];
            if (ShadingHooks.class.getClassLoader().getResource(variant) == null) {
                throw new IllegalArgumentException(hooks.name + "'s variant " + variant + " of " + hooks.replaced[i]
                    + " is not on the classpath");
            }
            variants.replace(hooks.replaced[i], variant);
        }
        variants.attach(ShadingHooks.class, hooks);
        return hooks;
    }

    /** The hooks installed on {@code device} ({@link #use}), else the engine's own. Allocates nothing. */
    public static ShadingHooks of(VulkanDevice device) {
        ShadingHooks installed = device.shaderVariants().attached(ShadingHooks.class);
        return installed != null ? installed : EngineShadingHooks.HOOKS;
    }

    /** The listing's name: its generated class's. */
    public String name() {
        return name;
    }

    /** The hooks by index. */
    public List<String> hooks() {
        return hooks;
    }

    /** Hook {@code hook}'s index, or -1 where the shaders were built without it. */
    public int index(String hook) {
        return hooks.indexOf(hook);
    }

    /**
     * Hook {@code hook}'s index.
     *
     * @throws IllegalStateException where the shaders were built without it: its project's listing is not installed
     */
    public int require(String hook) {
        int index = index(hook);
        if (index < 0) {
            throw new IllegalStateException("The shaders were built with the shading hooks of " + name + " " + hooks
                + ", without " + hook + ": install the listing of the project adding it (ShadingHooks.use)");
        }
        return index;
    }

    /** Hook {@code index}'s parameters' record class, or null for a hook without parameters. */
    public Class<?> parameters(int index) {
        return parameters[index];
    }

    /** The bytes of hook {@code index}'s parameters (0: none). */
    public int bytes(int index) {
        return bytes[index];
    }

    /** How many specialization constants the hooks' bits take, from {@link #FIRST_CONSTANT}. */
    public int words() {
        return words;
    }

    /** The bytes of a view's indirect-light table with these hooks: its fields, then an address per hook. */
    public long tableBytes() {
        return IndirectLightLayout.BYTES + 8L * hooks.size();
    }

    /** Where in a view's indirect-light table hook {@code index}'s parameters' address is. */
    public static long entry(int index) {
        if (index < 0) {
            throw new IndexOutOfBoundsException("Shading hook " + index);
        }
        return IndirectLightLayout.BYTES + 8L * index;
    }

    /**
     * Adds hook {@code hook} to the view building in {@code g}, its parameters from {@code source}: a record of the
     * view's, written each frame (a pass of the calling technique, which must list {@link Keys#INDIRECT_LIGHT} among
     * its {@link com.truesim.engine.graph.Technique#modifies}), its address in the view's table, and the hook turned
     * on for the view's shading ({@link IndirectInputs.Set#hook}). Returns the record's buffer, which shading reads.
     *
     * @throws IllegalStateException where the shaders were built without the hook, or its parameters' size is not the
     *     source's
     */
    @AllowAllocation("building the graph, when it changes")
    public Buffer add(GraphBuilder g, String hook, ShadingHookSource source) {
        int index = require(hook);
        int size = source.bytes();
        if (size != bytes[index]) {
            throw new IllegalStateException(hook + "'s parameters are " + bytes[index] + " bytes ("
                + (parameters[index] == null ? "none" : parameters[index].getSimpleName()) + "), its source's "
                + size);
        }
        Buffer table = g.modify(Keys.INDIRECT_LIGHT);
        Buffer record = size == 0 ? null : g.createBuffer(hook + " parameters", size);
        MemorySegment values = size == 0 ? null : Arena.ofAuto().allocate(size, 16);
        GraphBuilder.PassBuilder pass = g.pass(hook + " hook").write(table, BufferAccess.TRANSFER_DST);
        if (record != null) {
            pass.write(record, BufferAccess.TRANSFER_DST);
        }
        pass.record(ctx -> write(ctx, table, record, values, index, source));
        IndirectInputs.Set inputs = g.request(new IndirectInputs(g.view())).hook(index);
        if (record != null) {
            inputs.read(record);
        }
        return record;
    }

    /** The record's values as {@code source} has them now, and its address into the table. Allocates nothing. */
    private static void write(PassContext ctx, Buffer table, Buffer record, MemorySegment values, int index,
        ShadingHookSource source) {
        if (record == null) {
            return; // nothing to read: the hook has no parameters
        }
        source.write(ctx, values, 0);
        long handle = ctx.unsafe().buffer(record);
        long size = values.byteSize();
        for (long at = 0; at < size; at += 65_536) { // vkCmdUpdateBuffer takes 64 KiB at most
            Commands.updateBuffer(ctx.unsafe().commands(), handle, at, Math.min(65_536, size - at),
                values.address() + at);
        }
        try (MemoryStack stack = stackPush()) {
            long address = stack.nmalloc(8, 8);
            memPutLong(address, ctx.address(record));
            Commands.updateBuffer(ctx.unsafe().commands(), ctx.unsafe().buffer(table), entry(index), 8, address);
        }
    }

    @Override
    public String toString() {
        return name + hooks;
    }

    /**
     * The hooks a view's shading runs, a bit per hook index: its pipelines' specialization constants
     * ({@link #constants}). Immutable; equal masks make equal pipelines.
     */
    public static final class Mask {

        /** No hook. */
        public static final Mask NONE = new Mask(new int[0]);

        private final int[] words;

        private Mask(int[] words) {
            this.words = words;
        }

        /** This mask with hook {@code index} too. */
        @AllowAllocation("building the graph, when it changes")
        public Mask with(int index) {
            if (index < 0) {
                throw new IndexOutOfBoundsException("Shading hook " + index);
            }
            int[] more = Arrays.copyOf(words, Math.max(words.length, index / 32 + 1));
            more[index / 32] |= 1 << (index % 32);
            return new Mask(more);
        }

        /** Whether it holds hook {@code index}. */
        public boolean has(int index) {
            return index >= 0 && index / 32 < words.length && (words[index / 32] & 1 << (index % 32)) != 0;
        }

        /** Whether it holds no hook. */
        public boolean none() {
            for (int w : words) {
                if (w != 0) {
                    return false;
                }
            }
            return true;
        }

        /**
         * A pipeline's specialization constants: {@code own} at ids 0, 1, ... (its shader's own, at most
         * {@link #FIRST_CONSTANT}), then the mask's words from {@link #FIRST_CONSTANT}.
         */
        @AllowAllocation("building the graph, when it changes")
        public int[] constants(int... own) {
            if (own.length > FIRST_CONSTANT) {
                throw new IllegalArgumentException("A shader's own constants are ids 0 to " + (FIRST_CONSTANT - 1));
            }
            int length = words.length == 0 ? own.length : FIRST_CONSTANT + words.length;
            int[] constants = Arrays.copyOf(own, length);
            System.arraycopy(words, 0, constants, FIRST_CONSTANT, words.length);
            return constants;
        }

        @Override
        public boolean equals(Object o) {
            if (!(o instanceof Mask other)) {
                return false;
            }
            int n = Math.max(words.length, other.words.length);
            for (int i = 0; i < n; i++) {
                if ((i < words.length ? words[i] : 0) != (i < other.words.length ? other.words[i] : 0)) {
                    return false;
                }
            }
            return true;
        }

        @Override
        public int hashCode() {
            int h = 1;
            int last = words.length;
            while (last > 0 && words[last - 1] == 0) {
                last--;
            }
            for (int i = 0; i < last; i++) {
                h = 31 * h + words[i];
            }
            return h;
        }

        @Override
        public String toString() {
            return Arrays.toString(words);
        }
    }
}
