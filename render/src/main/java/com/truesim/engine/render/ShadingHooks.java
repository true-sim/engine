package com.truesim.engine.render;

import com.truesim.annotations.AllowAllocation;
import com.truesim.engine.graph.GraphBuilder;
import com.truesim.engine.render.layout.HooksConstants;
import com.truesim.engine.render.layout.ShadingHookBlockLayout;
import com.truesim.engine.vulkan.ShaderVariants;
import com.truesim.engine.vulkan.Specialization;
import com.truesim.engine.vulkan.VulkanDevice;
import java.lang.foreign.Arena;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.ValueLayout;
import java.lang.reflect.InvocationTargetException;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.ServiceLoader;

/**
 * The shading hooks the shaders were built with (hooks.slang; README, "Writing a shading hook"): each by its index, as
 * the generated dispatch numbers them, with its parameters' record. Hook {@code i} runs in a pipeline made with its
 * specialization constant ({@link #FIRST_SWITCH} + i) on ({@link #specialization}), and in a frame where its bit of the
 * view's hook block is set: its technique adds it ({@link #add}), or the scene holds values for it
 * ({@link ShadingHookValues}).
 *
 * <p>A listing is generated by the build for each project declaring hooks (engine-render's own,
 * {@link EngineShadingHooks}; a library's; a game's holding every hook it sees, with its libraries' shaders that shade
 * rebuilt with them) and found as a service ({@link ShadingHookListing}): the engine takes the one whose hooks contain
 * every other's and loads its variants in place of the libraries' shaders, before the device loads its first shader.
 * Two listings neither holding the other fail: the application then lists them all (its build's
 * {@code slang { shadingHooks = ... }}).
 *
 * <p>A view's hook block ({@link ShadingHookBlock}) holds every hook's record, its defaults where the view runs it
 * not, at offsets fixed by the listing ({@link #recordOffset}).
 */
public final class ShadingHooks {

    /** The id of hook 0's specialization constant: hooks.properties' {@code switch.first}. */
    public static final int FIRST_SWITCH = Specialization.REQUIRED_FROM;

    private static final ValueLayout.OfInt U32 = ValueLayout.JAVA_INT_UNALIGNED;

    private final String name;
    private final List<String> hooks;
    private final Class<?>[] parameters;
    private final int[] bytes;
    private final String[] replaced;
    private final int[] offsets; // of each record in a block
    private final long blockBytes;
    private final Specialization none; // every hook's switch off
    private MemorySegment defaults; // a block as made: the header, no bit set, every record's defaults (made lazily)
    private volatile ShadingHookParameters[] defaultRecords; // each hook's record's DEFAULTS (read lazily)

    private ShadingHooks(String name, List<String> hooks, Class<?>[] parameters, int[] bytes, String[] replaced) {
        this.name = name;
        this.hooks = hooks;
        this.parameters = parameters;
        this.bytes = bytes;
        this.replaced = replaced;
        int n = hooks.size();
        offsets = new int[n];
        long at = HooksConstants.SHADING_HOOK_HEADER + 4L * words(n) + 4L * n;
        for (int i = 0; i < n; i++) {
            at = (at + 15) / 16 * 16; // records 16-aligned, as their float4s may be
            offsets[i] = Math.toIntExact(at);
            at += bytes[i];
        }
        blockBytes = Math.max(16, (at + 15) / 16 * 16);
        Specialization off = Specialization.NONE;
        for (int i = 0; i < n; i++) {
            off = off.with(FIRST_SWITCH + i, 0);
        }
        none = off;
    }

    /**
     * A listing named {@code name}: {@code hooks} by index, each one's parameters' record class and bytes, the id of
     * hook 0's specialization constant, and {@code replaced}, pairs of a library's shader and its rebuilt variant
     * (classpath resources). Called by the generated listings.
     */
    @AllowAllocation("made once, by a generated class")
    public static ShadingHooks of(String name, String[] hooks, Class<?>[] parameters, int[] bytes, int firstSwitch,
        String[] replaced) {
        Objects.requireNonNull(name, "name");
        if (replaced.length % 2 != 0) {
            throw new IllegalArgumentException("Replaced shaders come in pairs: " + replaced.length);
        }
        if (parameters.length != hooks.length || bytes.length != hooks.length) {
            throw new IllegalArgumentException("A record and its bytes per hook");
        }
        if (firstSwitch != FIRST_SWITCH) {
            throw new IllegalArgumentException(name + " was built by other shading-hooks templates: switches from "
                + firstSwitch + ", not " + FIRST_SWITCH);
        }
        return new ShadingHooks(name, List.of(hooks), parameters.clone(), bytes.clone(), replaced.clone());
    }

    private static int words(int hooks) {
        return (hooks + 31) / 32;
    }

    // ---------------------------------------------------------------- which listing a device uses

    /**
     * Installs {@code hooks} on {@code device} in place of the one found on the classpath: its variants replace the
     * libraries' shaders wherever they are loaded, and {@link #of(VulkanDevice)} gives it. Returns {@code hooks}.
     *
     * @throws IllegalStateException once the device loaded a shader, or another listing is installed
     * @throws IllegalArgumentException where a variant is not on the classpath
     */
    @AllowAllocation("installed once, before rendering")
    public static ShadingHooks use(VulkanDevice device, ShadingHooks hooks) {
        ShaderVariants variants = device.shaderVariants();
        synchronized (variants) {
            ShadingHooks installed = variants.attached(ShadingHooks.class);
            if (installed == hooks) {
                return hooks;
            }
            if (installed != null) {
                throw new IllegalStateException("The device runs the shading hooks of " + installed.name
                    + " already: " + hooks.name + " would replace shaders some pipelines were made from");
            }
            install(variants, hooks);
            return hooks;
        }
    }

    /** {@code hooks}' variants in place of the shaders they replace, and {@code hooks} attached. */
    private static void install(ShaderVariants variants, ShadingHooks hooks) {
        for (int i = 0; i < hooks.replaced.length; i += 2) {
            String variant = hooks.replaced[i + 1];
            if (ShadingHooks.class.getClassLoader().getResource(variant) == null) {
                throw new IllegalArgumentException(hooks.name + "'s variant " + variant + " of " + hooks.replaced[i]
                    + " is not on the classpath");
            }
            variants.replace(hooks.replaced[i], variant);
        }
        variants.attach(ShadingHooks.class, hooks);
    }

    /**
     * The hooks {@code device} runs: those installed ({@link #use}), else the listing found on the classpath holding
     * every other one's (installed then, with its variants). Allocates nothing once installed.
     *
     * @throws IllegalStateException where two listings each lack hooks of the other
     */
    public static ShadingHooks of(VulkanDevice device) {
        ShaderVariants variants = device.shaderVariants();
        ShadingHooks installed = variants.attached(ShadingHooks.class);
        return installed != null ? installed : discover(variants);
    }

    /** Installs the classpath's listing on {@code variants}, unless one is installed; returns the one installed. */
    @AllowAllocation("installed once, before rendering")
    private static ShadingHooks discover(ShaderVariants variants) {
        synchronized (variants) {
            ShadingHooks installed = variants.attached(ShadingHooks.class);
            if (installed != null) {
                return installed;
            }
            List<ShadingHooks> found = new ArrayList<>();
            for (ShadingHookListing listing : ServiceLoader.load(ShadingHookListing.class,
                ShadingHooks.class.getClassLoader())) {
                found.add(listing.hooks());
            }
            ShadingHooks chosen = choose(found);
            if (variants.closed()) {
                variants.attach(ShadingHooks.class, chosen); // shaders loaded: only listings without variants fit
                if (chosen.replaced.length > 0) {
                    throw new IllegalStateException("The device loaded shaders before its shading hooks were chosen: "
                        + chosen.name + "'s variants come too late");
                }
            } else {
                install(variants, chosen);
            }
            return chosen;
        }
    }

    /**
     * The listing of {@code found} holding every other one's hooks (the engine's own where there is none).
     *
     * @throws IllegalStateException where two each lack hooks of the other
     */
    static ShadingHooks choose(List<ShadingHooks> found) {
        if (found.isEmpty()) {
            return EngineShadingHooks.HOOKS;
        }
        ShadingHooks best = found.getFirst();
        for (ShadingHooks other : found) {
            if (other.hooks.containsAll(best.hooks)) {
                best = other;
            }
        }
        for (ShadingHooks other : found) {
            if (!best.hooks.containsAll(other.hooks)) {
                String pkg = best.name.equals(other.name) ? "com.example.game" : "<your application's package>";
                throw new IllegalStateException("Shading hook listings " + best.name + " " + best.hooks + " and "
                    + other.name + " " + other.hooks + " each lack hooks of the other: list them all in one, by adding "
                    + "to the application's build.gradle.kts\n    slang { shadingHooks = \"" + pkg
                    + ".GameShadingHooks\" }\n(with the truesim.slang plugin), whose listing then holds every hook");
            }
        }
        return best;
    }

    /** Picks the listing for a device's variants before its first shader loads. A service. */
    public static final class Variants implements ShaderVariants.Installer {

        @Override
        public void install(ShaderVariants variants) {
            discover(variants);
        }
    }

    // ---------------------------------------------------------------- the hooks

    /** The listing's name: its generated class's. */
    public String name() {
        return name;
    }

    /** The hooks by index. */
    public List<String> hooks() {
        return hooks;
    }

    /** How many hooks there are. */
    public int count() {
        return hooks.size();
    }

    /** Hook {@code hook}'s index, or -1 where the shaders were built without it. */
    public int index(String hook) {
        return hooks.indexOf(hook);
    }

    /**
     * Hook {@code hook}'s index.
     *
     * @throws IllegalStateException where the shaders were built without it: the listing of the project adding it is
     *     not the one installed
     */
    public int require(String hook) {
        int index = index(hook);
        if (index < 0) {
            throw new IllegalStateException("The shaders were built with the shading hooks of " + name + " " + hooks
                + ", without " + hook + ": the listing of the project adding it must be on the classpath");
        }
        return index;
    }

    /** Hook {@code index}'s parameters' record class. */
    public Class<?> parameters(int index) {
        return parameters[index];
    }

    /** The bytes of hook {@code index}'s parameters. */
    public int bytes(int index) {
        return bytes[index];
    }

    /** Hook {@code index}'s parameters' defaults (its record's {@code DEFAULTS}). Allocates nothing once read. */
    public ShadingHookParameters defaults(int index) {
        ShadingHookParameters[] d = defaultRecords;
        return (d != null ? d : readDefaults())[index];
    }

    @AllowAllocation("read once")
    private ShadingHookParameters[] readDefaults() {
        ShadingHookParameters[] d = new ShadingHookParameters[count()];
        for (int i = 0; i < d.length; i++) {
            try {
                d[i] = (ShadingHookParameters) parameters[i].getField("DEFAULTS").get(null);
            } catch (ReflectiveOperationException e) {
                throw new IllegalStateException(parameters[i] + " is no generated hook record", e);
            }
        }
        defaultRecords = d;
        return d;
    }

    /** Hook {@code index}'s parameters from {@code values} by field name, defaults where they have none. */
    @AllowAllocation("values change rarely")
    public ShadingHookParameters fromValues(int index, MaterialValues values) {
        try {
            return (ShadingHookParameters) parameters[index].getMethod("fromValues", MaterialValues.class)
                .invoke(null, values);
        } catch (InvocationTargetException e) {
            if (e.getCause() instanceof RuntimeException runtime) {
                throw runtime;
            }
            throw new IllegalStateException(e.getCause());
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException(parameters[index] + " is no generated hook record", e);
        }
    }

    // ---------------------------------------------------------------- pipelines

    /**
     * A pipeline's constants: its shader's own ({@code own}, ids 0, 1, ...) and every hook's switch, on for the hooks
     * of {@code compiled}: vulkan's {@link Specialization} requires all those its shader declares.
     */
    @AllowAllocation("building the graph, when it changes")
    public Specialization specialization(Set compiled, int... own) {
        Specialization s = Specialization.of(own).with(none);
        for (int i = compiled.next(0); i >= 0 && i < count(); i = compiled.next(i + 1)) {
            s = s.with(FIRST_SWITCH + i, 1);
        }
        return s;
    }

    // ---------------------------------------------------------------- a view's block

    /** The bytes of a view's hook block: the header, the active bits, the offsets, every hook's record. */
    public long blockBytes() {
        return blockBytes;
    }

    /** Where in a view's block hook {@code index}'s record lies. */
    public int recordOffset(int index) {
        return offsets[index];
    }

    /** Where in a block the word holding hook {@code index}'s active bit lies. */
    public static long activeWord(int index) {
        return HooksConstants.SHADING_HOOK_HEADER + 4L * (index / 32);
    }

    /** A block as made: the header's count, the offsets, every hook's defaults, no hook active. Shared: read only. */
    @AllowAllocation("made once")
    synchronized MemorySegment defaultBlock() {
        if (defaults == null) {
            MemorySegment block = Arena.ofAuto().allocate(blockBytes, 16);
            int n = count();
            block.set(U32, ShadingHookBlockLayout.HOOKS, n);
            long table = HooksConstants.SHADING_HOOK_HEADER + 4L * words(n);
            for (int i = 0; i < n; i++) {
                block.set(U32, table + 4L * i, offsets[i]);
                defaults(i).write(block, offsets[i]);
            }
            defaults = block.asReadOnly();
        }
        return defaults;
    }

    // ---------------------------------------------------------------- a technique's hook

    /**
     * Adds hook {@code hook} to the view building in {@code g}, its parameters each frame from {@code source}: the
     * view's pipelines run it ({@link Set}) and its bit of the view's block is set in frames where the source is
     * {@link ShadingHookSource#active}. The calling technique must list {@link Keys#SHADING_HOOKS} among those it
     * modifies (so it builds before the view's shading); the technique adding a hook to a view is its only writer
     * there, merging what the scene holds for it ({@link ShadingHookValues}) with what only the frame knows. Returns the
     * view's hook inputs, for the hook's images and buffers shading reads ({@link ShadingHookInputs.Set#read}).
     *
     * @throws IllegalStateException where the shaders were built without the hook, its parameters' size is not the
     *     source's, or another technique added it to the view
     */
    @AllowAllocation("building the graph, when it changes")
    public ShadingHookInputs.Set add(GraphBuilder g, String hook, ShadingHookSource source) {
        int index = require(hook);
        if (source.bytes() != bytes[index]) {
            throw new IllegalStateException(hook + "'s parameters are " + bytes[index] + " bytes ("
                + parameters[index].getSimpleName() + "), its source's " + source.bytes());
        }
        g.modify(Keys.SHADING_HOOKS);
        return g.request(new ShadingHookInputs(g.view())).add(index, source);
    }

    @Override
    public String toString() {
        return name + hooks;
    }

    /**
     * Shading hooks by index: those a pipeline is made with, or a view runs. Immutable; equal sets make equal
     * pipelines.
     */
    public static final class Set {

        /** No hook. */
        public static final Set NONE = new Set(new long[0]);

        private final long[] words;

        private Set(long[] words) {
            int last = words.length;
            while (last > 0 && words[last - 1] == 0) {
                last--;
            }
            this.words = last == words.length ? words : Arrays.copyOf(words, last);
        }

        /** This set with hook {@code index} too. */
        @AllowAllocation("building the graph, when it changes")
        public Set with(int index) {
            if (index < 0) {
                throw new IndexOutOfBoundsException("Shading hook " + index);
            }
            long[] more = Arrays.copyOf(words, Math.max(words.length, index / 64 + 1));
            more[index / 64] |= 1L << (index % 64);
            return new Set(more);
        }

        /** The hooks of this set or {@code other}. */
        @AllowAllocation("building the graph, when it changes")
        public Set union(Set other) {
            long[] more = Arrays.copyOf(words, Math.max(words.length, other.words.length));
            for (int i = 0; i < other.words.length; i++) {
                more[i] |= other.words[i];
            }
            return new Set(more);
        }

        /** Whether it holds hook {@code index}. */
        public boolean has(int index) {
            return index >= 0 && index / 64 < words.length && (words[index / 64] & 1L << (index % 64)) != 0;
        }

        /** Whether it holds every hook of {@code other}. */
        public boolean containsAll(Set other) {
            for (int i = 0; i < other.words.length; i++) {
                long mine = i < words.length ? words[i] : 0;
                if ((other.words[i] & ~mine) != 0) {
                    return false;
                }
            }
            return true;
        }

        /** Whether it holds no hook. */
        public boolean none() {
            return words.length == 0;
        }

        /** The first hook from {@code from} it holds, or -1. */
        public int next(int from) {
            for (int i = Math.max(from, 0); i < 64 * words.length; i++) {
                if (has(i)) {
                    return i;
                }
            }
            return -1;
        }

        @Override
        public boolean equals(Object o) {
            return o instanceof Set other && Arrays.equals(words, other.words);
        }

        @Override
        public int hashCode() {
            return Arrays.hashCode(words);
        }

        @Override
        public String toString() {
            StringBuilder s = new StringBuilder("[");
            for (int i = next(0); i >= 0; i = next(i + 1)) {
                s.append(s.length() > 1 ? ", " : "").append(i);
            }
            return s.append(']').toString();
        }
    }
}
